// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { FormulaEngine, parseA1, type CellValue, type RawCell } from '../src/formula';

const a = (ref: string) => parseA1(ref)!;
const code = (v: CellValue) => (v instanceof Object ? v.code : v);

const data: RawCell[][] = [
  ['Region', 'Product', 'Qty', 'Price', 'Extra'],
  ['East', 'apple', 3, 1.5, 1],
  ['West', 'banana', 5, 0.25, '=1/0'],
  ['East', 'cherry', 10, 4, 3],
  ['North', 'Apricot', null, 2, 4],
  ['West', 'apple', 7, 1.5, 5],
];

function check(cases: [string, CellValue][]) {
  it.each(cases)('%s -> %s', (formula, expected) => {
    const e = FormulaEngine.buildFromArray(data);
    const v = code(e.calculateFormula(formula));
    if (typeof expected === 'number' && !Number.isInteger(expected)) expect(v).toBeCloseTo(expected, 10);
    else expect(v).toBe(expected);
  });
}

